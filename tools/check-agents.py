#!/usr/bin/env python3
"""Static check for awesome-novel-agent agent definitions

Validate the frontmatter of agents/*.md:
  1. Valid YAML
  2. skills/knowledge paths referenced in frontmatter really exist in the repository (or are deliberate placeholders/post-deployment paths)
  3. The tools field contains only legal tool names (when present)
  4. .claude/knowledge/ references are validated against the post-deployment layout (compared with init.deploy_knowledge products)

Additional checks (against broken links/orphans that are invisible inside the repository, arch-review 2026-08):
  5. knowledge references in the body text of skills/*.md: skills get inlined into the project, so repository-relative paths are guaranteed broken links
  6. Orphaned knowledge: files deployed into every project must be referenced by agents/skills/SKILL.md
  7. The skill.json files list includes knowledge/ (matching the install.sh copy scope)

Usage: python tools/check-agents.py
Exit code 0 = pass, non-zero = problems found (used by CI).

Rules:
- .md files under agents/ are agent source definitions in Claude Code syntax
- skills: reference skills/*.md (must exist)
- knowledge: two kinds of references:
    (a) Repository-relative paths (settings/, .claude/, etc., resolved from the repository root; must exist)
    (b) Post-deployment paths (.claude/knowledge/..., generated by init.py; the repository may have no source file)
  Class (b) gets a "path pattern" whitelist check; knowledge paths are additionally checked for existence against the deployed product list.
"""

