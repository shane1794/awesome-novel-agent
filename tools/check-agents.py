def _pct_sum_errors(d: dict, label: str, expected: float = 100, max_sum: float | None = None) -> list:
    """Percentage/distribution dict sum check: values must all be numeric (type excludes bool) and non-negative; all-zero means a placeholder to skip; non-zero values must sum to approximately expected (or be at most max_sum).

    String values (from the LLM or hand edits) are no longer silently skipped by `if total and`; non-numeric values error directly;
    negative values (e.g. {120,-20} faking a sum of 100) also error (review #19)."""
    bad = [k for k, v in d.items() if type(v) not in (int, float)]
    if bad:
        return [f"{label} values should be numeric (non-numeric keys: {sorted(bad)})"]
    neg = [k for k, v in d.items() if v < 0]
    if neg:
        return [f"{label} contains negative values (keys: {sorted(neg)})"]
    total = sum(d.values())
    if total == 0:
        return []                                  # all-zero placeholder (undistilled/empty override)
    if max_sum is not None:
        if total > max_sum:
            return [f"{label} total should be at most {max_sum} (currently {round(total)})"]
        return []
    if abs(total - expected) > 1:
        return [f"{label} sum should be about {expected} (currently {round(total)})"]
    return []


def check_style_card(path: Path, fm: dict | None = None) -> list:
    """Validate one style card. fm may be passed pre-parsed (review #43: check_style_cards parses once per batch call)."""
    errors = []
    text = path.read_text(encoding="utf-8-sig")   # utf-8-sig: strip the BOM (review #23, same convention as init)
    fm_text = _split_frontmatter(text)
    if fm_text is None:
        return [f"{path.name}: style card is missing frontmatter (needs two pairs of ---)"]
    for k in _dup_keys(fm_text):
        errors.append(f"{path.name}: duplicate YAML key {k!r} (last-wins silent overwrite)")
    if fm is None:
        try:
            fm = yaml.safe_load(fm_text)
        except Exception as e:
            return [f"{path.name}: card frontmatter YAML parse failed: {e}"]
    if not isinstance(fm, dict):
        return [f"{path.name}: card frontmatter is not a map"]
    for k in ("profile_version", "scene_type", "confidence", "last_updated", "source_sample_length"):
        if k not in fm:
            errors.append(f"{path.name}: card is missing {k}")
    st = fm.get("scene_type")
    if st not in STYLE_CARD_SCENE_TYPES:
        errors.append(f"{path.name}: scene_type={st!r} is not in the enum {sorted(STYLE_CARD_SCENE_TYPES)}")
    conf = fm.get("confidence")
    # Use type() instead of isinstance() to exclude bool (True/False are int subclasses and would slip through)
    if not type(conf) is int or not (0 <= conf <= 100):
        errors.append(f"{path.name}: confidence must be an integer in 0-100 (currently {conf!r})")
    # Schema discrimination (not by file name): override present means a scene card (sparse differences); otherwise a full 9-dimension card
    # (the main card and the genre-baselines base/benchmark/delta cards are all full schemas, with the latter using 0 as placeholder values).
    if "override" in fm:
        ov = fm.get("override")
        if not isinstance(ov, dict):
            errors.append(f"{path.name}: scene cards need an override field (dict, only the dimensions that differ from the main card)")
        else:
            for dim, ovd in ov.items():
                if dim not in STYLE_CARD_DIMS:
                    errors.append(f"{path.name}: override contains an unknown dimension {dim!r}")
                elif not isinstance(ovd, dict):
                    errors.append(f"{path.name}: override.{dim} must be a dict (currently {type(ovd).__name__})")
                else:
                    for k, v in ovd.items():          # value checks: negatives / out-of-range percentages (review #21)
                        if type(v) in (int, float) and not isinstance(v, bool):
                            if v < 0:
                                errors.append(f"{path.name}: override.{dim}.{k} is negative ({v!r})")
                            elif k.endswith(("_pct", "_ratio")) and v > 100:
                                errors.append(f"{path.name}: override.{dim}.{k} percentage out of range 0-100 ({v!r})")
    else:
        for dim in STYLE_CARD_DIMS:
            if dim not in fm:
                errors.append(f"{path.name}: card is missing dimension {dim}")
    bf = fm.get("baseline_for")
    if bf is not None and (not isinstance(bf, str) or not bf):
        errors.append(f"{path.name}: baseline_for must be a non-empty string (currently {bf!r})")
    locked = fm.get("locked")
    if locked is not None and not isinstance(locked, list):
        errors.append(f"{path.name}: locked must be a list")
    elif locked:
        for dim in locked:
            if dim not in STYLE_CARD_DIMS:
                errors.append(f"{path.name}: locked contains an unknown dimension {dim!r} (spec section 13-5#3)")
    inh = fm.get("inherits")
    if inh:
        # Inheritance target: a scene card inherits the main card (style-profiles/../writing-style.md) or a sibling scene card
        candidates = [path.parent / str(inh), path.parent.parent / str(inh)]
        if path.resolve() in {c.resolve() for c in candidates}:
            errors.append(f"{path.name}: inherits is self-referential (inheriting itself forms a cycle)")
        if not any(c.exists() for c in candidates):
            try:
                rels = "、".join(str(c.relative_to(ROOT)) for c in candidates)
            except ValueError:
                rels = "、".join(str(c) for c in candidates)  # path is not under ROOT (tests/external calls)
            errors.append(f"{path.name}: inherits reference does not exist: {inh} (expected {rels})")
    # --- Optional distilled-card enhancement fields (2026-08-12 dual states: validate only when present; missing fields stay compatible with old/undistilled cards) ---
    def _pct_ok(v):
        # Decision A unit check, single-sourced (style_common.pct_ok, review #39): 0-100 percentages (type excludes bool).
        # The old jieba engine produced 0-100 one-decimal percentages (13.4) with no 0-1 fraction assumption: 0.3 is 0.3%, not 30%.
        return pct_ok(v)

    def _pct_field(dim, field, val):
        errors.append(f"{path.name}: {dim}.{field} must be a 0-100 number (currently {val!r})")

    def _density_ok(v):
        """Density fields (X per hundred characters): any non-negative number works (review #18: density fields previously had no validation anywhere in the repository)."""
        return type(v) in (int, float) and not isinstance(v, bool) and v >= 0

    def _density_field(dim, field, val):
        errors.append(f"{path.name}: {dim}.{field} must be a non-negative number (currently {val!r})")

    lex = fm.get("lexicon") if isinstance(fm.get("lexicon"), dict) else {}
    for f in ("adj_density_per_100", "adv_density_per_100", "four_phrase_freq_per_100"):
        v = lex.get(f)
        if v is not None and not _density_ok(v):
            _density_field("lexicon", f, v)
    npr = lex.get("name_pronoun_ratio")
    if isinstance(npr, dict):
        keys = set(npr)
        if keys != {"name", "he_she", "i_you"}:
            errors.append(f"{path.name}: name_pronoun_ratio keys should be name/he_she/i_you (currently {sorted(keys)})")
        else:
            for e in _pct_sum_errors(npr, f"{path.name}: name_pronoun_ratio three-dimension sum"):
                errors.append(e)
    elif npr is not None and not _pct_ok(npr):
        errors.append(f"{path.name}: lexicon.name_pronoun_ratio scalar must be a 0-100 number (the old engine stored a name/pronoun ratio; currently {npr!r})")
    for wf in ("preferred_words", "banned_words"):
        wv = lex.get(wf)
        if wv is not None and not isinstance(wv, list):
            errors.append(f"{path.name}: lexicon.{wf} must be a list (currently {type(wv).__name__})")

    syn = fm.get("syntax") if isinstance(fm.get("syntax"), dict) else {}
    for f in ("single_sentence_paragraph_pct", "question_ratio", "exclamation_ratio"):
        v = syn.get(f)
        if v is not None and not _pct_ok(v):
            _pct_field("syntax", f, v)
    for f in ("avg_sentence_length", "avg_sentences_per_paragraph"):
        v = syn.get(f)
        if v is not None and not _density_ok(v):
            _density_field("syntax", f, v)
    dia = fm.get("dialogue_style") if isinstance(fm.get("dialogue_style"), dict) else {}
    if dia.get("subtext_ratio") is not None and not _pct_ok(dia["subtext_ratio"]):
        _pct_field("dialogue_style", "subtext_ratio", dia["subtext_ratio"])
    for f in ("avg_dialogue_length", "interrupt_freq_per_100"):
        v = dia.get(f)
        if v is not None and not _density_ok(v):
            _density_field("dialogue_style", f, v)

    em = fm.get("emotion_expression") if isinstance(fm.get("emotion_expression"), dict) else {}
    for f in ("direct_pct", "action_physiology_pct", "environment_projection_pct", "inner_monologue_pct"):
        v = em.get(f)
        if v is not None and not _pct_ok(v):
            _pct_field("emotion_expression", f, v)

    vs = fm.get("verb_style") if isinstance(fm.get("verb_style"), dict) else {}
    if vs.get("strength") not in (None, "", "weak", "medium", "strong"):
        errors.append(f"{path.name}: verb_style.strength should be weak/medium/strong (currently {vs.get('strength')!r})")
    for f in ("action_verb_ratio", "mental_verb_ratio", "state_verb_ratio"):
        v = vs.get(f)
        if v is not None and not _pct_ok(v):
            _pct_field("verb_style", f, v)

    coh = fm.get("cohesion") if isinstance(fm.get("cohesion"), dict) else {}
    if coh.get("transition_sentence_ratio") is not None and not _pct_ok(coh["transition_sentence_ratio"]):
        _pct_field("cohesion", "transition_sentence_ratio", coh["transition_sentence_ratio"])
    if coh.get("conjunction_freq_per_100") is not None \
            and not _density_ok(coh["conjunction_freq_per_100"]):
        _density_field("cohesion", "conjunction_freq_per_100", coh["conjunction_freq_per_100"])

    rhe = fm.get("rhetoric") if isinstance(fm.get("rhetoric"), dict) else {}
    if rhe.get("metaphor_density_per_100") is not None \
            and not _density_ok(rhe["metaphor_density_per_100"]):
        _density_field("rhetoric", "metaphor_density_per_100", rhe["metaphor_density_per_100"])

    for key in ("hard_constraints", "soft_guidance"):
        v = fm.get(key)
        if v is not None and not isinstance(v, list):
            errors.append(f"{path.name}: {key} must be a list")
    if fm.get("few_shot_examples") is not None and not isinstance(fm.get("few_shot_examples"), list):
        errors.append(f"{path.name}: few_shot_examples must be a list")

    rhy = fm.get("rhythm") if isinstance(fm.get("rhythm"), dict) else {}
    _FIVE = ("dialogue_pct", "action_pct", "environment_pct", "inner_thought_pct", "narration_pct")
    if "override" not in fm:
        missing = [f for f in _FIVE if f not in rhy]
        if missing:
            errors.append(f"{path.name}: rhythm is missing five-layer percentage keys {missing} (if any key is missing, the whole section check is skipped, review #20)")
    if all(f in rhy for f in _FIVE):
        five = {f: rhy[f] for f in _FIVE}
        for e in _pct_sum_errors(five, f"{path.name}: five-layer percentage total", max_sum=110):   # the five layers may overlap, cap 110% (spec section 5.1)
            errors.append(e)
        for f in _FIVE:                                                             # each bucket 0-100 (prevents dialogue_pct:110 from slipping through)
            if not _pct_ok(five[f]):
                _pct_field("rhythm", f, five[f])

    _DIST = {"syntax": ["sentence_length_dist"], "rhetoric": ["metaphor_preference", "sensory_dist"]}
    for dim, fields in _DIST.items():
        d = fm.get(dim) if isinstance(fm.get(dim), dict) else {}
        for f in fields:
            sub = d.get(f)
            if isinstance(sub, dict) and sub:
                for e in _pct_sum_errors(sub, f"{path.name}: {f} distribution sum"):
                    errors.append(e)
    return errors


def _resolve_inherits(p: Path, inh: str) -> Path | None:
    """Parse an inherits target (same two candidate paths as check_style_card) to the matching file or None."""
    for c in (p.parent / inh, p.parent.parent / inh):
        if c.exists():
            return c.resolve()
    return None


def check_style_cards() -> list:
    base = ROOT / "templates" / "settings"
    main = base / "writing-style.md"
    if not main.exists():
        return ["templates/settings/writing-style.md does not exist (old-layout repository?)"]
    cards = [main] + sorted((base / "style-profiles").rglob("*.md"))   # recursive: includes genre-baselines/**/base|benchmark|delta
    # Parse each card once (review #43: previously each card was parsed twice, once for validation and once for cycle detection)
    parsed: dict[str, dict] = {}
    for p in cards:
        fm_text = _split_frontmatter(p.read_text(encoding="utf-8-sig"))
        if fm_text:
            try:
                fm = yaml.safe_load(fm_text)
            except Exception:
                fm = {}
            parsed[str(p.resolve())] = fm if isinstance(fm, dict) else {}
    errors = []
    for p in cards:
        errors.extend(check_style_card(p, parsed.get(str(p.resolve()))))
    # Inheritance-cycle detection (cross-file DFS): an A to B to A cycle is not found by single-card existence checks
    graph = {}
    for key, fm in parsed.items():
        if fm.get("inherits"):
            tgt = _resolve_inherits(Path(key), fm["inherits"])
            graph[key] = str(tgt) if tgt else None
    _visited: set[str] = set()
    _cycles: set[str] = set()

    def _find_cycle(n: str, stack: list[str]) -> list[str] | None:
        if n in stack:
            return stack[stack.index(n):] + [n]
        if n in _visited or n not in graph:
            return None
        _visited.add(n)
        nxt = graph[n]
        if nxt:
            r = _find_cycle(nxt, stack + [n])
            if r:
                return r
        return None

    for start in list(graph):
        cyc = _find_cycle(start, [])
        if cyc:
            _cycles.add(" → ".join(cyc))
    for cyc in sorted(_cycles):
        errors.append(f"inherits cycle: {cyc}")
    return errors


def check_project_cards(project: Path) -> list:
    """Validate runtime project cards (settings/writing-style.md + settings/style-profiles/**).
    Repository template cards are validated by check_style_cards; project cards are style-distiller distillation products written to disk (review #18)."""
    base = project / "settings"
    if not base.exists():
        return []
    cards = []
    main = base / "writing-style.md"
    if main.exists():
        cards.append(main)
    profiles = base / "style-profiles"
    if profiles.exists():
        # analysis/ (quant tables + modeling rules + author portraits, no frontmatter) is not a style card, so exclude it to avoid false missing-frontmatter reports
        cards.extend(sorted(f for f in profiles.rglob("*.md") if "analysis" not in f.parts))
    errors = []
    for p in cards:
        errors.extend(check_style_card(p))
    return errors


def main() -> int:
    import argparse
    ap = argparse.ArgumentParser(description="Static check for agent definitions")
    ap.add_argument("--project", default=None,
                    help="Also validate runtime project cards (writing-style cards under settings/, style-distiller distillation products)")
    args = ap.parse_args()

    if not AGENTS_DIR.is_dir():
        print("⚠️  agents/ directory does not exist")
        return 1

    all_errors = []
    for f in sorted(AGENTS_DIR.glob("*.md")):
        errs = check_file(f)
        for e in errs:
            print(f"  ❌ {e}")
        all_errors.extend(errs)

    # .claude/agents tool-agent naming convention (review #53: {role}-agent.md)
    claude_agents = ROOT / ".claude" / "agents"
    if claude_agents.is_dir():
        for f in sorted(claude_agents.glob("*.md")):
            if not f.name.endswith("-agent.md"):
                msg = f".claude/agents/{f.name} does not follow the {role}-agent.md naming convention"
                print(f"  ❌ {msg}")
                all_errors.append(msg)

    # Validate that the skills files referenced by agents/ really exist in the skills/ directory
    refs = set()
    for f in AGENTS_DIR.glob("*.md"):
        text = f.read_text(encoding="utf-8-sig")
        for m in re.finditer(r"skills/([a-z-]+\.md)", text):
            refs.add(m.group(1))
    missing_skills = [r for r in sorted(refs) if not (SKILLS_DIR / r).exists()]
    for s in missing_skills:
        print(f"  ❌ missing skills reference: skills/{s}")
        all_errors.append(f"skills/{s}")

    # Post-deployment knowledge layout validation + orphan detection + skill.json completeness (arch-review 2026-08)
    for label, errs in (
        ("knowledge references", check_deployed_knowledge_refs()),
        ("orphans", check_orphan_knowledge()),
        ("skill.json", check_skill_json()),
    ):
        for e in errs:
            print(f"  ❌ [{label}] {e}")
        all_errors.extend(errs)

    style_errs = check_style_cards()
    for e in style_errs:
        print(f"  ❌ {e}")
    all_errors.extend(style_errs)

    if args.project:
        proj_errs = check_project_cards(Path(args.project))
        for e in proj_errs:
            print(f"  ❌ [project] {e}")
        all_errors.extend(proj_errs)

    if all_errors:
        print(f"\n{len(all_errors)} problem(s) in total")
        return 1
    print("✅ All agent definitions passed")
    return 0


