# Post-deployment knowledge layout validation (arch-review 2026-08)
# ---------------------------------------------------------------
# init.deploy_knowledge's product layout differs from the repository knowledge/ layout:
#   format-specs/*.md          → <root>/knowledge/*.md (flattened)
#   genre-example/{genre}.md   → <root>/knowledge/genre-example.md (merged)
#   anti-ai four sources + genre rules → <root>/knowledge/anti-ai.md (merged)
#   craft directories + style-distill/ → <root>/knowledge/<directory>/ (copied as-is)
# References use post-deployment paths (base .claude/knowledge/..., with rewrite_refs rewriting the prefix per platform),
# and there is no source file in the repository, so the product list can only be validated by computing it from the init.py logic.

# Generated products: init.py generates them on every run (referencing them is legal)
_KNOWLEDGE_GENERATED = {"anti-ai.md", "genre-example.md", "permanent-memory.md"}

# Reference files in the repository knowledge/ aimed at the author and not consumed by agents (exempt from the deployment list, whitelisted for orphan detection)
_KNOWLEDGE_AUTHOR_REFS = {
    "knowledge/anti-ai/fanqie.md",       # 1200+ lines of author study material, which states that AI does not read it proactively
    "knowledge/README.md",               # knowledge base self-description
    "knowledge/genre-example/index.md",  # genre registry (the data source init uses to pick a genre, not a deployment product)
    "knowledge/plot-craft/README.md",
    "knowledge/scene-craft/README.md",
    "knowledge/scene-craft/index.md",
    "knowledge/title-craft/index.md",    # SKILL.md title-craft methodology (referenced from the author-interaction entry point)
}


def _deployed_knowledge_files() -> set[str] | None:
    """Simulate init.deploy_knowledge to compute the post-deployment <root>/knowledge/ product list (a set of relative paths).

    Import init directly to reuse its real logic (including the ensure_yaml platform check) so this list cannot drift from init.
    Simulate both lengths and take the union: short-form knowledge (short-*) and long-form products are both legal deployment products,
    and simulating only long would misjudge short-form knowledge as orphaned references (design D7).
    init depends on pyyaml; return None when it is missing, and the caller skips this check group (CI has pyyaml installed).
    """
    try:
        import init as init_mod
    except ImportError:
        return None
    if PLATFORM_CLAUDE is None:
        return None
    files: set[str] = set()
    for length, genre in ((None, "xianxia"), ("short", "zhuiqi")):
        with tempfile.TemporaryDirectory() as td:
            tmp = Path(td)
            fake_project = tmp / "proj"
            fake_project.mkdir()
            # deploy_knowledge assumes the knowledge directory already exists (the init flow creates it first via create_skeleton)
            PLATFORM_CLAUDE.knowledge_dir(fake_project).mkdir(parents=True, exist_ok=True)
            with contextlib.redirect_stdout(io.StringIO()):
                init_mod.deploy_knowledge(fake_project, genre, PLATFORM_CLAUDE, length)
            know = fake_project / ".claude" / "knowledge"
            if not know.is_dir():
                return None
            files |= {p.relative_to(know).as_posix() for p in know.rglob("*") if p.is_file()}
    return files


def check_deployed_knowledge_refs() -> list:
    """Validate that knowledge references in agents frontmatter + skills body text really exist under the post-deployment layout.

    - Base references are written as `.claude/knowledge/<relative path>`; rewrite_refs only replaces the prefix, so the relative path is the product path
    - References with {} (e.g. scene-craft/{genre}.md) only check that the directory exists
    - A repository-relative path (knowledge/format-specs/...) appearing in skills body text means a guaranteed broken link (skills get inlined into the project)
    """
    files = _deployed_knowledge_files()
    if files is None:
        return []                      # skip in scenarios such as missing pyyaml (CI has pyyaml)
    errors = []

    # knowledge paths in agents frontmatter (only the .claude/knowledge/ prefix is checked;
    # settings/, story.md, .agent/ and other entries are handled by check_file's whitelist logic)
    for f in sorted(AGENTS_DIR.glob("*.md")):
        fm = _parse_frontmatter(f)
        if fm is None:
            continue
        for entry in fm.get("knowledge") or []:
            if not isinstance(entry, dict):
                continue
            rel = str(entry.get("path") or "")
            if rel.startswith(".claude/knowledge/"):
                err = _check_knowledge_ref(rel[len(".claude/knowledge/"):], files, f"{f.name} frontmatter")
                if err:
                    errors.append(err)

    # knowledge references in agents body text (agent definitions deploy into the project, so references follow the same base rule)
    for f in sorted(AGENTS_DIR.glob("*.md")):
        text = f.read_text(encoding="utf-8-sig")
        for m in re.finditer(r"\.claude/knowledge/([A-Za-z0-9_./{}-]+)", text):
            err = _check_knowledge_ref(m.group(1), files, f"{f.name} body text")
            if err:
                errors.append(err)
        for m in re.finditer(r"(?<![.a-zA-Z0-9_/-])knowledge/(format-specs|genre-example|anti-ai)/"
                             r"([A-Za-z0-9_./{}-]+)", text):
            errors.append(
                f"{f.name}: body text references the repository-relative path knowledge/{m.group(1)}/{m.group(2)},"
                f"which does not exist after deployment (format-specs flattened / genre-example merged / anti-ai merged;"
                f"please rewrite it as a .claude/knowledge/ base path)"
            )

    # knowledge references in skills body text (skills are inlined into reasonix/zcode/dsh/codex products, so references follow the same rule)
    for f in sorted(SKILLS_DIR.glob("*.md")):
        text = f.read_text(encoding="utf-8-sig")
        for m in re.finditer(r"\.claude/knowledge/([A-Za-z0-9_./{}-]+)", text):
            err = _check_knowledge_ref(m.group(1), files, f"{f.name} body text")
            if err:
                errors.append(err)
        # A repository-relative knowledge/ reference means it was not written against the post-deployment base, so it will break after inlining (roleplay-sandbox class of problem)
        for m in re.finditer(r"(?<![.a-zA-Z0-9_/-])knowledge/(format-specs|genre-example|anti-ai)/"
                             r"([A-Za-z0-9_./{}-]+)", text):
            errors.append(
                f"{f.name}: body text references the repository-relative path knowledge/{m.group(1)}/{m.group(2)},"
                f"which does not exist after deployment (format-specs flattened / genre-example merged / anti-ai merged;"
                f"please rewrite it as a .claude/knowledge/ base path)"
            )

    # References in the body text of deployed knowledge files (same roleplay-sandbox broken-link class; repository-only docs
    # README/index/fanqie are not in the deployed product set, so they are skipped automatically)
    for repo_path in sorted((ROOT / "knowledge").rglob("*.md")):
        rel = _repo_knowledge_to_deployed(repo_path)
        if rel is None or rel not in files:
            continue
        text = repo_path.read_text(encoding="utf-8-sig")
        where = f"{repo_path.relative_to(ROOT)} body text"
        for m in re.finditer(r"\.claude/knowledge/([A-Za-z0-9_./{}-]+)", text):
            err = _check_knowledge_ref(m.group(1), files, where)
            if err:
                errors.append(err)
        for m in re.finditer(r"(?<![.a-zA-Z0-9_/-])knowledge/([A-Za-z0-9_./{}-]+)", text):
            ref = m.group(1).rstrip("/")
            if not ref or "{" in ref:
                continue
            # craft directories deploy as-is, but their files must still go through the .claude/knowledge/ base;
            # there is no bare knowledge/ directory at the project root (see the roleplay-sandbox broken-link problem with the same cause)
            errors.append(
                f"{where}: references the repository-relative path knowledge/{ref}, which does not exist after deployment"
                f"(format-specs flattened / genre-example merged / anti-ai merged;"
                f"please rewrite it as a .claude/knowledge/ base path)"
            )
    return errors


def _repo_knowledge_to_deployed(repo_path: Path) -> str | None:
    """Repository knowledge/ file to post-deployment relative path; files that are not deployed return None."""
    rel = repo_path.relative_to(ROOT / "knowledge")
    if rel.parts[0] == "format-specs":
        return rel.name                      # flattened to the knowledge/ root
    if rel.parts[0] in ("plot-craft", "scene-craft", "character-craft",
                        "title-craft", "style-distill"):
        return rel.as_posix()                # directories copied as-is
    return None                              # README/index/fanqie/anti-ai genre sources and similar are not deployed directly


def _parse_frontmatter(path: Path) -> dict | None:
    """agent .md frontmatter to dict; no frontmatter / parse failure / non-map to None."""
    text = path.read_text(encoding="utf-8-sig")
    fm_text = _split_frontmatter(text)
    if fm_text is None:
        return None
    try:
        fm = yaml.safe_load(fm_text)
    except Exception:
        return None
    return fm if isinstance(fm, dict) else None


def _check_knowledge_ref(base: str, files: set[str], where: str) -> str | None:
    """A single knowledge reference to an error message or None. base is the relative path under the post-deployment knowledge/ directory
    (it may end with / to mean a directory-level reference, or contain {} placeholders)."""
    base = base.replace("\\", "/").strip()
    if not base or base in _KNOWLEDGE_GENERATED:
        return None                     # anti-ai.md / genre-example.md / permanent-memory.md are always generated
    if base.endswith("/") or "{" in base:
        # Directory-level references (scene-craft/) or placeholders (scene-craft/{genre}.md) check that the directory exists
        d = base if base.endswith("/") else base.rsplit("/", 1)[0]
        if not any(x == d.rstrip("/") or x.startswith(d) for x in files):
            return f"{where}: knowledge reference to directory {base} is not in the deployed products"
        return None
    if base not in files:
        return f"{where}: knowledge reference {base} is not in the deployed products (init.deploy_knowledge does not generate it)"
    return None


def check_orphan_knowledge() -> list:
    """Every knowledge file deployed into each project must be referenced by agents/skills/SKILL.md.

    Product files (the 3 generated products such as anti-ai.md) are created by the deployment logic and count as consumed.
    """
    deployed = _deployed_knowledge_files()
    if deployed is None:
        return []
    # Collect all repository references (agents frontmatter + agents/skills/SKILL.md body text, extracting .claude/knowledge/ paths uniformly)
    referenced: set[str] = set(_KNOWLEDGE_GENERATED)
    sources = list(AGENTS_DIR.glob("*.md")) + list(SKILLS_DIR.glob("*.md")) + [ROOT / "SKILL.md"]
    # References in the body text of deployed knowledge files also count as consumption (e.g. chapter-quality-checklist to writing-style.md)
    sources += [p for p in (ROOT / "knowledge").rglob("*.md")
                if _repo_knowledge_to_deployed(p) in deployed]
    for f in sources:
        if not f.exists():
            continue
        text = f.read_text(encoding="utf-8-sig")
        for m in re.finditer(r"\.claude/knowledge/([A-Za-z0-9_./{}-]+)", text):
            referenced.add(m.group(1))
        # SKILL.md repository-relative references (title-craft) also count as consumption
        for m in re.finditer(r"(?<![.a-zA-Z0-9_/-])knowledge/((?:plot|scene|character|title)-craft/"
                             r"[A-Za-z0-9_./{}-]+)", text):
            referenced.add(m.group(1))
        # Directory-level references (.claude/knowledge/scene-craft/) consume every file in that directory;
        # Placeholder references (.claude/knowledge/short-genres/{genre}.md) work the same way; both count as "directory-level consumption"
        for m in re.finditer(r"\.claude/knowledge/((?:plot|scene|character|title)-craft|style-distill|short-craft|short-genres)/(?:\{[^}]+\}\.md)?", text):
            referenced.add(m.group(1) + "/")
    errors = []
    for rel in sorted(deployed):
        if rel in _KNOWLEDGE_AUTHOR_REFS:
            continue
        if any(rel.startswith(d) for d in referenced if d.endswith("/")):
            continue                    # covered by a directory-level reference
        if rel in referenced:
            continue
        errors.append(
            f"Orphaned knowledge: {rel} is deployed into every project but no agent/skill/SKILL.md references it"
            f"(wire it up or delete it; if it is genuinely an author reference, add it to the _KNOWLEDGE_AUTHOR_REFS exemption)"
        )
    # Exempt files inside the repository are also copied into the project with the craft directories (copytree), so they likewise need a reference or an explicit exemption
    # (already covered by the deployed set above: README/index belong to _KNOWLEDGE_AUTHOR_REFS, and the rest follow the same rule).
    return errors


def check_skill_json() -> list:
    """Consistency between the skill.json packaging list and the install.sh copy scope."""
    sj = ROOT / "skill.json"
    if not sj.exists():
        return []
    try:
        data = json.loads(sj.read_text(encoding="utf-8"))
    except Exception as e:
        return [f"skill.json parse failed: {e}"]
    errors = []
    files = data.get("files") or []
    if "knowledge/" not in files:
        errors.append(
            "skill.json files is missing knowledge/ (install.sh copies knowledge/,"
            "packaging by this list would lose the entire knowledge base)"
        )
    return errors


