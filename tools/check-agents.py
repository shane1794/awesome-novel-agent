# Legal tool names (Claude Code tools whitelist)
VALID_TOOLS = {
    "Read", "Write", "Edit", "Glob", "Grep", "Bash", "PowerShell",
    "WebFetch", "WebSearch", "NotebookEdit", "TodoWrite", "AskUserQuestion",
    "Skill", "Agent", "Task",
}

# Path patterns generated after deployment that may have no source file in the repository (whitelist; file existence not required)
# These are generated by init.py per genre / by merging, or created by the updater when archiving
# (review #47: the first item was fully covered by `[a-z-]+\.md`, so it was redundant and deleted)
DEPLOYED_PATTERNS = [
    re.compile(r"^\.claude/knowledge/[a-z-]+\.md$"),          # flattened products (format-specs/anti-ai/genre-example/permanent-memory)
    re.compile(r"^\.claude/knowledge/(plot-craft|scene-craft|character-craft|title-craft|style-distill)/"),
    re.compile(r"^\.claude/knowledge/(short-craft|short-genres)/"),  # short-form knowledge directories (craft/genres subdirectory copies)
    re.compile(r"^sandbox/(prose-regressions|locked-lines)\.txt$"),  # project sandbox assets (shared long/short-form convention)
    re.compile(r"^stories/"),                                  # short-form story directories (one subdirectory per story)
    re.compile(r"^settings/character-setting/"),               # one file per character
    re.compile(r"^settings/(world-setting|genre-setting|writing-style|timeline|foreshadowing)\.md$"),
    re.compile(r"^settings/style-profiles/"),               # per-scene style cards (one file per scene)
    re.compile(r"^settings/\.style-versions/"),             # distillation version snapshot directory (created when style-distiller backs up a distillation)
    re.compile(r"^\.agent/"),                                  # runtime state
    re.compile(r"^story\.md$"),
    re.compile(r"^volumes/"), re.compile(r"^chapters/"), re.compile(r"^prompts/"), re.compile(r"^archives/"),
]


def _split_frontmatter(text: str) -> str | None:
    """Extract the frontmatter body text (between the two --- lines; single-source implementation in style_common.frontmatter_text, review #38)."""
    return frontmatter_text(text)


def _dup_keys(fm_text: str) -> list[str]:
    """Detect duplicate top-level frontmatter YAML keys: yaml.safe_load is last-wins silent overwrite
    (confidence flipping silently from 0 to 80), so detect them independently before parsing (review #22)."""
    try:
        node = yaml.compose(fm_text)
    except Exception:
        return []
    if not isinstance(node, yaml.MappingNode):
        return []
    seen: set[str] = set()
    dup: list[str] = []
    for k, _v in node.value:
        key = k.value if isinstance(k, yaml.ScalarNode) else ""
        if key in seen:
            dup.append(key)
        seen.add(key)
    return dup


def check_file(path: Path) -> list:
    errors = []
    text = path.read_text(encoding="utf-8-sig")   # utf-8-sig: strip the BOM (review #23, same convention as init)
    if not text.startswith("---"):
        return [f"{path.name}: missing frontmatter (must start with ---)"]

    fm_text = _split_frontmatter(text)
    if fm_text is None:
        return [f"{path.name}: frontmatter not closed correctly (needs two pairs of ---)"]

    for k in _dup_keys(fm_text):
        errors.append(f"{path.name}: duplicate YAML key {k!r} (last-wins silent overwrite)")

    try:
        fm = yaml.safe_load(fm_text)
    except Exception as e:
        return [f"{path.name}: frontmatter YAML parse failed: {e}"]

    if not isinstance(fm, dict):
        return [f"{path.name}: frontmatter is not a YAML map"]

    # name is required
    if "name" not in fm:
        errors.append(f"{path.name}: missing name field")

    # tools field validity
    tools = fm.get("tools")
    if tools:
        names = [t.strip() for t in str(tools).split(",") if t.strip()]
        bad = [t for t in names if t not in VALID_TOOLS]
        if bad:
            errors.append(f"{path.name}: tools contains illegal tool names {bad} (legal: {sorted(VALID_TOOLS)})")

    # skills / knowledge path existence
    for key in ("skills", "knowledge"):
        entries = fm.get(key) or []
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            p = entry.get("path")
            if not p:
                continue
            rel = str(p)
            # Placeholders (e.g. {genre}) are skipped; init.py replaces them or they belong to merged products
            if "{" in rel:
                continue
            # Post-deployment paths use whitelist mode and do not require the file to exist, but settings/*.md must have a matching template
            if _is_deployed(rel):
                if rel.startswith("settings/") and rel.endswith(".md"):
                    # Per-character dynamic files (character-setting/) are not template-checked
                    if not rel.startswith("settings/character-setting/"):
                        tpl = ROOT / "templates" / rel
                        if not tpl.exists():
                            errors.append(
                                f"{path.name}: references settings/ path {rel}, but templates/settings/ has no matching template"
                                f"(a new project's init.py will not generate it, so it will definitely be missing at runtime)"
                            )
                continue
            target = ROOT / rel
            if not target.exists():
                errors.append(f"{path.name}: references a non-existent {key} path: {rel}")

    return errors


def _is_deployed(rel: str) -> bool:
    """Check whether a path matches the "generated after deployment, no source in the repository" pattern."""
    rel = rel.replace("\\", "/")
    # .md files under skills/ in the repository must really exist (the skill sources live in the repository)
    if rel.startswith("skills/") or rel.startswith("knowledge/"):
        return False
    for pat in DEPLOYED_PATTERNS:
        if pat.match(rel):
            return True
    return False


